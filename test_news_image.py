import os
from images.image_engine import ImageEngine


# ------------------------------------------------------------
# 1) إنشاء محرك الصور
# ------------------------------------------------------------
image_engine = ImageEngine()

# ------------------------------------------------------------
# 2) بيانات تجريبية (Dummy Data)
# ------------------------------------------------------------
template = "news"

image_data = {
    "headline": "Microsoft تعلن نتائج مالية تجاوزت التوقعات",
    "body": (
        "أعلنت Microsoft عن نتائج فصلية قوية مدعومة بنمو خدمات الذكاء الاصطناعي "
        "والحوسبة السحابية، مما أدى إلى ارتفاع السهم في تداولات ما قبل الافتتاح."
    ),
    "category": "Earnings",
    "session": "PRE_MARKET",
    "timestamp": "2026-08-01 08:30 ET",
    "source": "Business Wire"
}

text_message = (
    "📰 خبر مهم\n\n"
    "أعلنت Microsoft نتائج مالية فاقت توقعات السوق، "
    "بدعم من نمو أعمال Azure والذكاء الاصطناعي.\n\n"
    "📌 التأثير المتوقع:\n"
    "• إيجابي على قطاع التكنولوجيا.\n"
    "• قد يدعم أسهم MSFT وNASDAQ عند الافتتاح.\n\n"
    "المصدر: Business Wire"
)

# ------------------------------------------------------------
# 3) تنفيذ الاختبار
# ------------------------------------------------------------
print("🔧 بدء اختبار قالب الأخبار...")

output_path = image_engine.build_image(template, image_data)

# ------------------------------------------------------------
# 4) التحقق من نجاح إنشاء الصورة
# ------------------------------------------------------------
if output_path:
    print("✅ build_image() أعاد مسارًا صالحًا.")
    print(f"📁 المسار: {output_path}")
else:
    print("❌ فشل إنشاء الصورة — build_image() أعاد None.")
    exit()

# ------------------------------------------------------------
# 5) التحقق من وجود الملف فعليًا
# ------------------------------------------------------------
if os.path.exists(output_path):
    print("✅ ملف الصورة موجود فعليًا في النظام.")
else:
    print("❌ ملف الصورة غير موجود رغم أن build_image() أعاد مسارًا.")
    exit()

# ------------------------------------------------------------
# 6) طباعة النص
# ------------------------------------------------------------
print("\n📄 النص المرسل:")
print(text_message)

print("\n🎉 الاختبار الأول (News) اكتمل بنجاح!")
