import os
from images.image_engine import ImageEngine

# ------------------------------------------------------------
# 1) إنشاء محرك الصور
# ------------------------------------------------------------
image_engine = ImageEngine()

# ------------------------------------------------------------
# 2) بيانات Breaking الحقيقية (مطابقة لـ NewsEngine)
# ------------------------------------------------------------
template = "breaking"

image_data = {
    "headline": "انفجار قوي يهز منطقة صناعية في ولاية ميشيغان الأمريكية",
    "body": "أفادت التقارير الأولية بوقوع انفجار في منشأة صناعية، وتجري السلطات تقييم الأضرار.",
    "category": "Breaking",
    "session": "MARKET_OPEN",
    "timestamp": "2026-08-01 03:45 AST",
    "source": "Reuters"
}

text_message = (
    "🚨 خبر عاجل\n\n"
    "انفجار قوي يهز منطقة صناعية في ولاية ميشيغان الأمريكية، "
    "وتشير التقارير الأولية إلى وقوع أضرار مادية كبيرة.\n\n"
    "📌 التصنيف: Breaking\n"
    "المصدر: Reuters"
)

# ------------------------------------------------------------
# 3) تنفيذ الاختبار
# ------------------------------------------------------------
print("🔧 بدء اختبار قالب الأخبار العاجلة...")

output_path = image_engine.build_image(template, image_data)

# ------------------------------------------------------------
# 4) التحقق من نجاح إنشاء الصورة
# ------------------------------------------------------------
if output_path:
    print("✅ build_image() أعاد مسارًا صالحًا.")
    print(f"📁 المسار: {output_path}")
else:
    raise RuntimeError("❌ فشل إنشاء الصورة — build_image() أعاد None.")

# ------------------------------------------------------------
# 5) التحقق من وجود الملف فعليًا
# ------------------------------------------------------------
if os.path.exists(output_path):
    print("✅ ملف الصورة موجود فعليًا في النظام.")
else:
    raise FileNotFoundError(f"❌ ملف الصورة غير موجود: {output_path}")

# ------------------------------------------------------------
# 6) طباعة النص
# ------------------------------------------------------------
print("\n📄 النص المرسل:")
print(text_message)

print("\n🎉 الاختبار الثالث (Breaking) اكتمل بنجاح!")
