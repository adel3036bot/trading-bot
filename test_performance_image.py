import os
from images.image_engine import ImageEngine

# ------------------------------------------------------------
# 1) إنشاء محرك الصور
# ------------------------------------------------------------
image_engine = ImageEngine()

# ------------------------------------------------------------
# 2) بيانات Performance الحقيقية
# ------------------------------------------------------------
template = "performance"

image_data = {
    "total_trades": 18,
    "winning_trades": 15,
    "losing_trades": 3,
    "win_rate": 83.3,
    "average_profit": 245,
    "total_profit": 4410,
    "moon_shots": 4,
    "legendary_trades": 1,
    "best_symbol": "MSFT"
}

text_message = (
    "🌙 تقرير نهاية اليوم\n\n"
    "📊 إجمالي الصفقات: 18\n"
    "🏆 نسبة الفوز: 83.3%\n"
    "💰 إجمالي الربح: $4410\n"
    "🚀 صفقات Moonshot: 4\n"
    "👑 صفقات Legendary: 1\n"
    "⭐ أفضل رمز تداول: MSFT"
)

# ------------------------------------------------------------
# 3) تنفيذ الاختبار
# ------------------------------------------------------------
print("🔧 بدء اختبار قالب الأداء...")

output_path = image_engine.build_image(template, image_data)

# ------------------------------------------------------------
# 4) التحقق من نجاح إنشاء الصورة
# ------------------------------------------------------------
if output_path:
    print("✅ build_image() أعاد مسارًا صالحًا.")
    print(f"📁 المسار: {output_path}")
else:
    raise RuntimeError("❌ فشل إنشاء الصورة — build_image() أعاد None.")

# ------------------------------------------------------------
# 5) التحقق من وجود الملف فعليًا
# ------------------------------------------------------------
if os.path.exists(output_path):
    print("✅ ملف الصورة موجود فعليًا في النظام.")
else:
    raise FileNotFoundError(f"❌ ملف الصورة غير موجود: {output_path}")

# ------------------------------------------------------------
# 6) طباعة النص
# ------------------------------------------------------------
print("\n📄 النص المرسل:")
print(text_message)

print("\n🎉 الاختبار الثاني (Performance) اكتمل بنجاح!")
